"""Bootstrap the application database: create all tables, then stamp Alembic.

``alembic upgrade head`` cannot initialize a database in this project. The
migration chain was generated as *patches* on top of a schema that
``db.create_all()`` had already built: the base revision alters ``users``
without ever creating it, the next one alters ``db_connections`` the same
way, and a later revision drops a long-gone developer-local ``certificate``
table. On an empty database the chain dies at the first revision, and on a
database built by today's models it would collide with existing columns.

The supported initialization path is therefore:

    1. create every table from the current models  (``db.create_all()``)
    2. mark the database as fully migrated         (``alembic stamp head``)

After that ``alembic current`` reports head, and any future autogenerated
revision applies normally on top.

Usage
-----
    python scripts/bootstrap_db.py
    python scripts/bootstrap_db.py --url postgresql://user:pass@host:5432/db

The URL comes from ``--url`` or the ``DATABASE_URL`` environment variable.
The process environment wins over ``backend/.env``, exactly like
``seed_demo.py``.

The script is idempotent: existing tables are skipped and the stamp is
rewritten, so it can be re-run safely at any time.

Safety
------
The script refuses to run against a database that holds the demo tables
(``customers``, ``orders``, ``order_items``, ``products``) - the demo
database is seeded by ``scripts/seed_demo.py``, and this script would only
pollute it with the application's own tables.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

from dotenv import load_dotenv

BACKEND_DIR = Path(__file__).resolve().parent.parent

# Read backend/.env so DATABASE_URL is picked up without exporting it by
# hand. Existing environment variables win - load_dotenv never overrides.
load_dotenv(BACKEND_DIR / ".env")

# Tables that mean "this is the demo database, hands off".
DEMO_TABLES = {"customers", "products", "orders", "order_items"}


def masked(url: str) -> str:
    """Render a connection URL with its password hidden."""
    parts = urlsplit(url)
    netloc = parts.netloc
    if "@" in netloc:
        userinfo, host = netloc.rsplit("@", 1)
        user = userinfo.split(":", 1)[0]
        netloc = f"{user}:****@{host}"
    return urlunsplit(parts._replace(netloc=netloc))


def resolve_url(args: argparse.Namespace) -> str:
    url = args.url or os.environ.get("DATABASE_URL") or ""
    if not url:
        raise SystemExit(
            "No target URL. Pass --url or set DATABASE_URL "
            "(e.g. postgresql://postgres.<ref>:<pass>@aws-1-ap-northeast-2"
            ".pooler.supabase.com:5432/postgres)."
        )
    return url


def assert_not_demo(conn, database_name: str) -> None:
    """Refuse to bootstrap a database that holds the demo tables."""
    with conn.cursor() as cur:
        cur.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_schema = 'public' AND table_type = 'BASE TABLE'"
        )
        existing = {row[0] for row in cur.fetchall()}

    clash = existing & DEMO_TABLES
    if clash:
        raise SystemExit(
            f"Refusing to bootstrap {database_name!r}: it holds demo tables "
            f"{sorted(clash)}. That is the demo database - seed it with "
            "scripts/seed_demo.py, never point the app's own database at it."
        )


def create_tables() -> list[str]:
    """Create every table from the current models; return their names."""
    if str(BACKEND_DIR) not in sys.path:
        sys.path.insert(0, str(BACKEND_DIR))

    from sqlalchemy import inspect

    from app import create_app
    from extensions import db

    app = create_app()
    with app.app_context():
        db.create_all()
        return sorted(inspect(db.engine).get_table_names())


def stamp_head() -> None:
    """Write the head revision into alembic_version without running anything."""
    from alembic import command
    from alembic.config import Config

    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "migrations"))
    command.stamp(cfg, "head")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Create all app tables from the models and stamp Alembic at head."
    )
    parser.add_argument(
        "--url",
        default=None,
        help="Target database URL. Defaults to the DATABASE_URL environment variable.",
    )
    args = parser.parse_args(argv)

    url = resolve_url(args)
    # env.py resolves the raw-CLI URL from the process environment first;
    # pin it so the stamp below targets exactly the database printed above.
    os.environ["DATABASE_URL"] = url

    database_name = urlsplit(url).path.lstrip("/")
    if not database_name:
        raise SystemExit(f"Could not read a database name from {masked(url)}")

    print(f"Target database: {database_name}  ({masked(url)})")

    import psycopg2

    conn = psycopg2.connect(url)
    try:
        assert_not_demo(conn, database_name)
    finally:
        conn.close()

    print("Creating tables from the current models ...")
    tables = create_tables()
    print(f"  tables: {', '.join(tables) if tables else '(none)'}")

    print("Stamping Alembic at head ...")
    stamp_head()

    print("Done. 'alembic current' should now report head (0fd86f3183c9).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
